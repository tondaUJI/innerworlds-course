function pick(i){
  const t=T[lang],q=quiz.qs[quiz.n],ok=i===q[2],last=quiz.n===quiz.qs.length-1;
  quiz.score+=ok;
  $('qb').querySelectorAll('.opt').forEach((b,j)=>{b.disabled=true;if(j===q[2])b.classList.add('ok');else if(j===i)b.classList.add('no')});
  $('qf').innerHTML=`<p class="fb"><b>${ok?t.right:t.wrong}</b> ${q[3]}</p><div class="act"><button class="btn" type="button" id="qn">${last?t.finish:t.next}</button></div>`;
  $('qn').focus();
  $('qn').onclick=()=>{quiz.n++;last?showResult():showQ()};
}
