function openQuiz(m,k){
  quiz={m,k,qs:(QZ[lang]||QZ.en)[m][k],n:0,score:0};
  showQ();
  if(!$('qd').open)$('qd').showModal();
}
function showQ(){
  const t=T[lang],{m,k,qs,n}=quiz,q=qs[n];
  $('qb').innerHTML=`<div class="qh"><span class="pill">${t.A[k]}</span><span>${t.qOf.replace('{n}',n+1).replace('{t}',qs.length)}</span></div>
    <div class="bar"><i style="width:${n/qs.length*100}%"></i></div>
    <p class="qt">${M[m][lang][0]}</p><p class="qq">${q[0]}</p>
    <div class="opts">${q[1].map((o,i)=>`<button type="button" class="opt" data-o="${i}"><b>${LET[i]}</b><span>${o}</span></button>`).join('')}</div><div id="qf"></div>`;
  $('qb').querySelectorAll('.opt').forEach(b=>b.onclick=()=>pick(+b.dataset.o));
}
function pick(i){
  const t=T[lang],q=quiz.qs[quiz.n],ok=i===q[2],last=quiz.n===quiz.qs.length-1;
  quiz.score+=ok;
  $('qb').querySelectorAll('.opt').forEach((b,j)=>{b.disabled=true;if(j===q[2])b.classList.add('ok');else if(j===i)b.classList.add('no')});
  $('qf').innerHTML=`<p class="fb"><b>${ok?t.right:t.wrong}</b> ${q[3]}</p><div class="act"><button class="btn" type="button" id="qn">${last?t.finish:t.next}</button></div>`;
  $('qn').focus();
  $('qn').onclick=()=>{quiz.n++;last?showResult():showQ()};
}
async function showResult(){
  const t=T[lang],{m,k,qs,score}=quiz,pct=Math.round(score/qs.length*100);
  $('qb').innerHTML=`<div class="res"><div class="ring" style="--p:${pct}"><span>${score}/${qs.length}</span></div>
    <h3>${pct>=80?t.msgHi:pct>=50?t.msgMid:t.msgLow}</h3><p id="qr" role="status"></p>
    <div class="act"><button class="btn" type="button" id="qa">${t.retry}</button><button class="btn alt" type="submit">${t.close}</button></div></div>`;
  $('qa').onclick=()=>openQuiz(m,k);
  if(user){
    const {error}=await sb.from('quiz_results').upsert({user_id:user.id,module:m,audience:k,score,total:qs.length,updated_at:new Date().toISOString()});
    if(error)$('qr').textContent=`${t.err}: ${error.message}`;else{$('qr').textContent=t.saved;res[m+k]={score,total:qs.length};paintBadges()}
  }else if(sb)$('qr').textContent=t.loginToSave;
}
